#include "libft.h"

void	ft_bzero(void *s, size_t n)
{
	char			*a;
	unsigned long	i;

	a = s;
	i = 0;
	while (n > 0)
	{
		a[i] = '\0';
		i++;
		n--;
	}
	s = a;
}

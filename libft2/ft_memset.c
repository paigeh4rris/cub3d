#include "libft.h"

void	*ft_memset(void *s, int c, size_t n)
{
	char	*a;
	int		i;

	a = s;
	i = 0;
	while (n > 0)
	{
		a[i] = (unsigned char) c;
		i++;
		n--;
	}
	s = a;
	return (s);
}
